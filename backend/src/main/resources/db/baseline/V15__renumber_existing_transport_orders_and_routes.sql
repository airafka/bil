-- One-time renumbering explicitly requested for existing records.
-- Relations use UUIDs; preserve all fields other than the display number.
LOCK TABLE receiving_order, shipping_order, route IN ACCESS EXCLUSIVE MODE;
CREATE TEMP TABLE renumber_orders ON COMMIT DROP AS
SELECT kind, id, (28547 + row_number() OVER (ORDER BY number, kind, id))::integer AS new_number
FROM (SELECT 'receiving' AS kind, id, number FROM receiving_order
      UNION ALL SELECT 'shipping', id, number FROM shipping_order) orders;
CREATE TEMP TABLE renumber_routes ON COMMIT DROP AS
SELECT id, (21325 + row_number() OVER (ORDER BY number, id))::integer AS new_number FROM route;
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM receiving_order WHERE number <= 0)
       OR EXISTS (SELECT 1 FROM shipping_order WHERE number <= 0)
       OR EXISTS (SELECT 1 FROM route WHERE number <= 0) THEN
        RAISE EXCEPTION 'Renumbering requires positive existing numbers';
    END IF;
END $$;
-- Temporary negative values avoid unique-key conflicts with numbers already in the target range.
UPDATE receiving_order r SET number = -m.new_number FROM renumber_orders m WHERE m.kind = 'receiving' AND m.id = r.id;
UPDATE shipping_order s SET number = -m.new_number FROM renumber_orders m WHERE m.kind = 'shipping' AND m.id = s.id;
UPDATE receiving_order SET number = -number;
UPDATE shipping_order SET number = -number;
ALTER TABLE route ALTER COLUMN number SET GENERATED BY DEFAULT;
UPDATE route r SET number = -m.new_number FROM renumber_routes m WHERE m.id = r.id;
UPDATE route SET number = -number;
ALTER TABLE route ALTER COLUMN number SET GENERATED ALWAYS;
DO $$ DECLARE next_order bigint; next_route bigint; BEGIN
    SELECT 28548 + count(*) INTO next_order FROM renumber_orders;
    SELECT 21326 + count(*) INTO next_route FROM renumber_routes;
    EXECUTE format('ALTER SEQUENCE transport_order_number_seq RESTART WITH %s', next_order);
    EXECUTE format('ALTER SEQUENCE route_code_seq RESTART WITH %s', next_route);
END $$;
